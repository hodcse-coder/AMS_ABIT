-- PostgreSQL translation of the Academics tables in ABITDB.sql.
CREATE TABLE IF NOT EXISTS lessonplan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 title BIGINT DEFAULT NULL,
 PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS lessonplans (
 lessonplan_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 subjectteacher_id BIGINT NOT NULL,
 subjectteacher_subject_id BIGINT NOT NULL,
 module BIGINT NOT NULL,
 topics text NOT NULL,
 bookname text NOT NULL,
 pagenumber BIGINT NOT NULL,
 ppt_req varchar(1) NOT NULL,
 ppt text NOT NULL,
 video_url text NOT NULL,
 co text NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 updated_at TIMESTAMPTZ DEFAULT NULL,
 updated_by BIGINT DEFAULT NULL,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (lessonplan_id)
);
CREATE TABLE IF NOT EXISTS lessonplan_detail (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 lessonplan_id BIGINT DEFAULT NULL,
 item_name text DEFAULT NULL,
 lesson_co text DEFAULT NULL,
 lesson_book text DEFAULT NULL,
 book_page BIGINT NOT NULL DEFAULT 0,
 ppt_required BIGINT NOT NULL DEFAULT 0,
 ppt_url varchar(150) DEFAULT NULL,
 ppt_status BIGINT NOT NULL DEFAULT 0,
 video_url text DEFAULT NULL,
 lplan_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS lessonplan_docs (
 lessonplan_docs_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 lessonplan_docs_details varchar(100) DEFAULT NULL,
 lessonplan_docs_lessonplan_detail_id BIGINT DEFAULT NULL,
 lessonplan_master_id BIGINT DEFAULT NULL,
 lessonplan_docs_path varchar(150) DEFAULT NULL,
 lessonplan_docs_submited_at TIMESTAMPTZ DEFAULT NULL,
 lessonplan_docs_status SMALLINT NOT NULL DEFAULT 0,
 created_by BIGINT DEFAULT NULL,
 reviewed_by BIGINT DEFAULT NULL,
 reviewed_at TIMESTAMPTZ DEFAULT NULL,
 PRIMARY KEY (lessonplan_docs_id)
);
CREATE TABLE IF NOT EXISTS co_defined (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 cotype text NOT NULL,
 PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS courseoutcome (
 co_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 cotype text NOT NULL,
 co_subject_id BIGINT NOT NULL,
 codescription text NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 updated_at TIMESTAMPTZ DEFAULT NULL,
 updated_by BIGINT DEFAULT NULL,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (co_id)
);
CREATE TABLE IF NOT EXISTS faculty_books (
 book_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 faculty_id BIGINT NOT NULL,
 subject_id BIGINT NOT NULL,
 book_name text NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 updated_at TIMESTAMPTZ DEFAULT NULL,
 updated_by BIGINT DEFAULT NULL,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (book_id)
);
CREATE TABLE IF NOT EXISTS lecture_notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 teacher BIGINT NOT NULL,
 subject BIGINT NOT NULL,
 sem BIGINT NOT NULL,
 description text NOT NULL,
 attachment text NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 updated_at TIMESTAMPTZ DEFAULT NULL,
 updated_by BIGINT DEFAULT NULL,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS subjectteacher (
 subjectteacher_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 subjectteacher_subject_id BIGINT NOT NULL,
 subjectteacher_employee_id BIGINT NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 updated_at TIMESTAMPTZ DEFAULT NULL,
 updated_by BIGINT DEFAULT NULL,
 ppt_reviewer BIGINT DEFAULT NULL,
 lessonplan_exempted SMALLINT NOT NULL DEFAULT 1,
 study_material_exempted SMALLINT NOT NULL DEFAULT 0,
 study_material SMALLINT NOT NULL DEFAULT 1,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (subjectteacher_id)
);
CREATE TABLE IF NOT EXISTS videolecture (
 l_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 related_subject BIGINT NOT NULL,
 brief_description text NOT NULL,
 video_url TEXT NOT NULL,
 created_at TIMESTAMPTZ DEFAULT NULL,
 created_by BIGINT NOT NULL,
 reviewed_at TIMESTAMPTZ DEFAULT NULL,
 reviewed_by BIGINT DEFAULT NULL,
 is_status SMALLINT NOT NULL DEFAULT 0,
 PRIMARY KEY (l_id)
);
CREATE TABLE IF NOT EXISTS student_attendance (
 student_attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 student_attendance_date date DEFAULT NULL,
 student_attendance_classstarttime text NOT NULL,
 student_attendance_classendtime text NOT NULL,
 student_attendance_lessonplan_id BIGINT NOT NULL,
 student_attendance_student_id BIGINT NOT NULL,
 student_attendance_present_absent BIGINT NOT NULL,
 student_attendance_master_id BIGINT NOT NULL,
 student_attendance_user_id BIGINT NOT NULL,
 shst_master_id BIGINT NOT NULL,
 shst_course_id BIGINT NOT NULL,
 shst_batch_id BIGINT NOT NULL,
 shst_semester BIGINT NOT NULL,
 shst_section_house_type varchar(1) NOT NULL,
 shst_section_house_id BIGINT NOT NULL,
 shst_subject_id BIGINT NOT NULL,
 shst_subject_type varchar(1) NOT NULL,
 shst_teacher_emp_info_id BIGINT NOT NULL,
 shst_teacher_emp_master_id BIGINT NOT NULL,
 shst_teacher_user_id BIGINT NOT NULL,

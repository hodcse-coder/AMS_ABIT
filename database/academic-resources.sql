);
CREATE TABLE IF NOT EXISTS section_house_subject_teacher (
 shst_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
 shst_course_id BIGINT NOT NULL,
 shst_batch_id varchar(100) NOT NULL,
 shst_semester BIGINT NOT NULL,
 shst_section_house_type varchar(1) NOT NULL,
 shst_section_house_id BIGINT NOT NULL,
 shst_semester_master_id BIGINT NOT NULL,
 shst_subject_id BIGINT NOT NULL,
 shst_teacher_id BIGINT NOT NULL,
